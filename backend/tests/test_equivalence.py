"""End-to-end numerical equivalence against the original TensorFlow model.

This is the test that separates "the service returns numbers" from "the service
returns the right numbers". It runs a real checkpoint through the *whole* pipeline —
validation, encoding, tiling, forward, stitching, track selection — and compares
against predictions generated by the original TensorFlow Shorkie.

The fixture holds genomic sequences (chunk 009). Chunks 000-004 of the source dataset
are synthetic random DNA whose activations are ~12x smaller; a precision regression
would hide there.
"""

from __future__ import annotations

import os
from pathlib import Path

import numpy as np
import pytest

from app import engine as EN
from app.core.encode import dna_1hot
from app.core.spec import SHORKIE
from app.core.tracks import load_catalog

FIXTURE = Path(__file__).parent / "fixtures" / "shorkie_golden.npz"
DEFAULT_CHECKPOINT = Path(__file__).parents[3] / "shorkie-pytorch" / "data" / "checkpoint_f0.h5"
DEFAULT_PARAMS = Path(__file__).parents[3] / "shorkie-pytorch" / "data" / "shorkie_params.json"


def checkpoint_paths() -> tuple[Path, Path]:
    return (
        Path(os.getenv("SHORKIE_CHECKPOINT", DEFAULT_CHECKPOINT)),
        Path(os.getenv("SHORKIE_PARAMS", DEFAULT_PARAMS)),
    )


requires_weights = pytest.mark.skipif(
    not checkpoint_paths()[0].exists(),
    reason="set SHORKIE_CHECKPOINT to the fold-0 checkpoint to run equivalence tests",
)


@pytest.fixture(scope="module")
def golden():
    return np.load(FIXTURE, allow_pickle=False)


@pytest.fixture(scope="module")
def adapter():
    from app.models.shorkie import ShorkieAdapter

    weights, params = checkpoint_paths()
    ad = ShorkieAdapter(weights, params)
    ad.load("cpu")
    return ad


class TestEncoderIsPinnedToTheReferenceInput:
    """Guards against a circular test: decoding and re-encoding with the same table
    would cancel out any permutation of the channel order."""

    def test_service_encoder_reproduces_the_tensor_tf_was_fed(self, golden):
        for seq, reference in zip(golden["sequences"], golden["onehot"]):
            assert np.array_equal(dna_1hot(str(seq)), reference.T.astype(np.float32))

    def test_reference_is_acgt_ordered_not_a_permutation(self, golden):
        # Real yeast DNA is ~38% GC. Any A/T <-> C/G swap would read as ~50%.
        oh = golden["onehot"]
        gc = (oh[:, :, 1].sum() + oh[:, :, 2].sum()) / oh[:, :, 0].size
        assert 0.30 < gc < 0.45

    def test_reference_has_no_ambiguous_positions(self, golden):
        # decode maps an all-zero column to N; assert there are none rather than
        # relying on the generator having skipped windows containing them.
        assert (golden["onehot"].sum(axis=2) == 1).all()


@requires_weights
class TestEquivalence:
    def test_model_is_in_eval_mode(self, adapter):
        # from_tf_checkpoint returns a train-mode model; one forward in that state is
        # noise AND permanently rewrites the BatchNorm buffers.
        assert not adapter._model.training

    def test_full_pipeline_matches_tensorflow(self, golden, adapter):
        seqs = [str(s) for s in golden["sequences"]]
        gold = golden["predictions"]                     # (n, 896, 64)
        track_idx = golden["track_indices"]

        catalog = load_catalog("shorkie")
        selection = catalog.resolve(SHORKIE, tracks=[int(i) for i in track_idx])
        plans = EN.plan(
            [EN.SequenceInput(str(i), s) for i, s in enumerate(seqs)],
            SHORKIE,
            selection,
            window="native",
        )
        result = EN.run(plans, adapter, selection, limits=EN.Limits(micro_batch=2))

        assert len(result.predictions) == len(seqs)
        max_abs = 0.0
        for n, prediction in enumerate(result.predictions):
            assert prediction.window == "native"
            assert prediction.start_bp == SHORKIE.crop_bp
            assert prediction.n_bins == SHORKIE.n_bins

            got = prediction.values.T                    # (896, 64), rows are tracks
            expected = gold[n]
            max_abs = max(max_abs, float(np.abs(got - expected).max()))

            r = np.corrcoef(got.ravel(), expected.ravel())[0, 1]
            assert r > 0.999999, f"sequence {n}: pearson {r}"
            assert np.allclose(got, expected, rtol=1e-3, atol=1e-4), f"sequence {n}"

        # Measured ~1e-4 for fp32 on this port; ~1e-2 would mean TF32 or autocast crept
        # back in. A relative-only gate would pass a whole track being 0.1% off, so
        # keep an absolute backstop too.
        assert max_abs < 1e-3, f"max abs deviation {max_abs:.3e}"

    def test_repeated_forward_is_bit_identical(self, golden, adapter):
        # A train-mode forward would mutate the BatchNorm buffers and make the second
        # call differ. Order-dependent corruption is otherwise invisible.
        onehot = dna_1hot(str(golden["sequences"][0]))[None]
        first = adapter.forward(onehot, golden["track_indices"])
        second = adapter.forward(onehot, golden["track_indices"])
        assert np.array_equal(first, second)

    def test_batching_does_not_change_results(self, golden, adapter):
        # Sequences from different callers share a forward pass; a batch-dependent
        # result would make responses depend on unrelated traffic.
        onehot = np.stack([dna_1hot(str(s)) for s in golden["sequences"][:2]])
        alone = adapter.forward(onehot[:1], golden["track_indices"])
        together = adapter.forward(onehot, golden["track_indices"])
        assert np.array_equal(alone[0], together[0])

    def test_tile_extracted_from_a_longer_sequence_matches_tensorflow(self, golden, adapter):
        """The strong form of the tiling test.

        Embed a golden 16384 bp sequence inside a longer one at an offset chosen so
        that one tile's window is byte-identical to the golden window, then assert the
        model output for that tile matches TensorFlow. Comparing merged output instead
        would prove nothing: with one tile the merge is a division by 1.0.
        """
        from app.core.coords import tile_onehot
        from app.core.encode import dna_1hot

        seq = str(golden["sequences"][0])
        # A tile at origin o spans [o - crop_bp, o - crop_bp + seq_length), so a 6144 bp
        # prefix puts the tile at origin 7168 exactly over the embedded sequence.
        prefix, suffix = "A" * 6144, "C" * 4096
        long_seq = prefix + seq + suffix
        origin = len(prefix) + SHORKIE.crop_bp
        assert origin % SHORKIE.bin_size == 0

        tile = tile_onehot(dna_1hot(long_seq), origin, SHORKIE)
        assert np.array_equal(tile, dna_1hot(seq)), "tile window is not the golden window"

        got = adapter.forward(tile[None], golden["track_indices"])[0]
        assert np.allclose(got, golden["predictions"][0], rtol=1e-3, atol=1e-4)
